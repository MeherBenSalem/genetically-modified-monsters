"""Keyframe animations, written once in Python and generated as vanilla AnimationDefinitions.

Semantics match net.minecraft.client.animation exactly:
- rotation keyframes are degrees added to the bone's rest rotation (KeyframeAnimations.degreeVec);
- position keyframes are pixels added to the pivot, **+y up** (KeyframeAnimations.posVec flips y);
- scale keyframes are absolute multipliers (KeyframeAnimations.scaleVec subtracts 1);
- "catmullrom" interpolation is the smooth one (use it for nearly everything), "linear" for snaps.

  a = Anim("walk", 1.0, loop=True)
  a.rot("left_leg", (0, 20, 0, 0), (0.5, -20, 0, 0), (1.0, 20, 0, 0))     # (time, x, y, z)
  a.wave("body", "rot", axis=2, amplitude=4, period=1.0)                    # smooth sine loop
"""
from __future__ import annotations

import math
from dataclasses import dataclass, field

TARGETS = {"rot": "ROTATION", "pos": "POSITION", "scale": "SCALE"}
VEC = {"rot": "degreeVec", "pos": "posVec", "scale": "scaleVec"}


@dataclass
class Key:
    t: float
    v: tuple[float, float, float]
    interp: str = "catmullrom"


@dataclass
class Anim:
    name: str
    length: float
    loop: bool = False
    channels: dict[tuple[str, str], list[Key]] = field(default_factory=dict)

    def _add(self, bone: str, kind: str, keys, interp: str):
        chan = self.channels.setdefault((bone, kind), [])
        for k in keys:
            t, x, y, z = k[:4]
            it = k[4] if len(k) > 4 else interp
            chan.append(Key(float(t), (float(x), float(y), float(z)), it))
        chan.sort(key=lambda k: k.t)
        return self

    def rot(self, bone: str, *keys, interp: str = "catmullrom") -> "Anim":
        return self._add(bone, "rot", keys, interp)

    def pos(self, bone: str, *keys, interp: str = "catmullrom") -> "Anim":
        return self._add(bone, "pos", keys, interp)

    def scale(self, bone: str, *keys, interp: str = "catmullrom") -> "Anim":
        return self._add(bone, "scale", keys, interp)

    def wave(self, bone: str, kind: str, axis: int, amplitude: float, period: float | None = None,
             phase: float = 0.0, base: float | None = None, steps: int = 8) -> "Anim":
        """A smooth looping sine on one axis (adds keys over the whole length; period defaults to the length)."""
        period = period or self.length
        rest = base if base is not None else (1.0 if kind == "scale" else 0.0)
        n = max(2, round(self.length / period * steps))
        keys = []
        for i in range(n + 1):
            t = self.length * i / n
            value = rest + amplitude * math.sin(2 * math.pi * (t / period + phase))
            vec = [rest if kind == "scale" else 0.0] * 3
            vec[axis] = value
            keys.append((t, *vec))
        existing = self.channels.get((bone, kind))
        if existing:
            # Merge onto an existing channel on another axis: sample it at the same times.
            merged = []
            for t, *vec in keys:
                cur = sample(existing, t, self.loop, self.length)
                out = list(cur)
                out[axis] = vec[axis]
                merged.append((t, *out))
            self.channels[(bone, kind)] = []
            return self._add(bone, kind, merged, "catmullrom")
        return self._add(bone, kind, keys, "catmullrom")

    def java(self, const: str) -> str:
        lines = [f"    public static final AnimationDefinition {const} = AnimationDefinition.Builder.withLength({self.length:.4f}F)"]
        if self.loop:
            lines[-1] += ".looping()"
        for (bone, kind), keys in self.channels.items():
            kf = ",\n".join(
                f"                    new Keyframe({k.t:.4f}F, KeyframeAnimations.{VEC[kind]}({k.v[0]:.4f}F, {k.v[1]:.4f}F, {k.v[2]:.4f}F), "
                f"AnimationChannel.Interpolations.{'CATMULLROM' if k.interp == 'catmullrom' else 'LINEAR'})"
                for k in keys)
            lines.append(f"            .addAnimation(\"{bone}\", new AnimationChannel(AnimationChannel.Targets.{TARGETS[kind]},\n{kf}))")
        lines.append("            .build();")
        return "\n".join(lines)


def java_animations(package: str, class_name: str, creature: str, anims: list[Anim]) -> str:
    body = "\n\n".join(a.java(a.name.upper()) for a in anims)
    return "\n".join([
        "// GENERATED by tools/assets/ss/entities from the creature's animations. Do not edit; run tools/assets/build.py.",
        f"package {package};",
        "",
        "import net.minecraft.client.animation.AnimationChannel;",
        "import net.minecraft.client.animation.AnimationDefinition;",
        "import net.minecraft.client.animation.Keyframe;",
        "import net.minecraft.client.animation.KeyframeAnimations;",
        "",
        f"/** Keyframed animations of the {creature.replace('_', ' ')}. */",
        f"public final class {class_name} {{",
        f"    private {class_name}() {{",
        "    }",
        "",
        body,
        "}",
        "",
    ])


# ---- sampling (same maths as vanilla) for previews -------------------------------------------------------------------

def _catmull(t: float, p0: float, p1: float, p2: float, p3: float) -> float:
    return 0.5 * (2.0 * p1 + (p2 - p0) * t + (2.0 * p0 - 5.0 * p1 + 4.0 * p2 - p3) * t * t
                  + (3.0 * p1 - p0 - 3.0 * p2 + p3) * t * t * t)


def sample(keys: list[Key], t: float, loop: bool, length: float) -> tuple[float, float, float]:
    """KeyframeAnimations.animate: find the keyframe pair around t and interpolate (clamped at the ends)."""
    if loop and length > 0:
        t = t % length
    i = max(0, next((n for n, k in enumerate(keys) if k.t > t), len(keys)) - 1)
    j = min(len(keys) - 1, i + 1)
    a, b = keys[i], keys[j]
    span = b.t - a.t
    alpha = 0.0 if span <= 0 else max(0.0, min(1.0, (t - a.t) / span))
    if b.interp == "catmullrom":
        p0 = keys[max(0, i - 1)].v
        p3 = keys[min(len(keys) - 1, j + 1)].v
        return tuple(_catmull(alpha, p0[n], a.v[n], b.v[n], p3[n]) for n in range(3))
    return tuple(a.v[n] + (b.v[n] - a.v[n]) * alpha for n in range(3))


def pose_at(anims: list[Anim], t: float, weights: dict[str, float] | None = None) -> dict[str, dict[str, tuple]]:
    """Bone -> {"rot": deg, "pos": px (y up), "scale": abs} offsets at time t, summed over the given animations."""
    pose: dict[str, dict[str, list[float]]] = {}
    for a in anims:
        w = (weights or {}).get(a.name, 1.0)
        for (bone, kind), keys in a.channels.items():
            v = sample(keys, t, a.loop, a.length)
            slot = pose.setdefault(bone, {})
            if kind == "scale":
                cur = slot.get(kind, [1.0, 1.0, 1.0])
                slot[kind] = [cur[n] + (v[n] - 1.0) * w for n in range(3)]
            else:
                cur = slot.get(kind, [0.0, 0.0, 0.0])
                slot[kind] = [cur[n] + v[n] * w for n in range(3)]
    return {b: {k: tuple(v) for k, v in d.items()} for b, d in pose.items()}
