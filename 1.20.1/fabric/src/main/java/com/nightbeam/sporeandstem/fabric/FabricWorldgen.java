package com.nightbeam.sporeandstem.fabric;

import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import com.nightbeam.sporeandstem.SporeAndStem;
import net.fabricmc.fabric.api.biome.v1.BiomeModifications;
import net.fabricmc.fabric.api.biome.v1.BiomeSelectors;
import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.core.registries.Registries;
import net.minecraft.resources.ResourceKey;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.tags.TagKey;
import net.minecraft.world.entity.EntityType;
import net.minecraft.world.entity.MobCategory;
import net.minecraft.world.level.biome.Biome;
import net.minecraft.world.level.levelgen.GenerationStep;
import net.minecraft.world.level.levelgen.placement.PlacedFeature;

import java.io.IOException;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.io.Reader;
import java.nio.charset.StandardCharsets;
import java.util.Locale;

/**
 * Adds the placed features and spawns to biomes by the shared biome tags. The table is generated by
 * tools/assets/ss/worldgen.py into {@value #MANIFEST}, the same source the NeoForge biome modifiers come from, so the
 * two loaders always match. Biome membership lives in data ({@code #spore_and_stem:has_feature/*},
 * {@code #spore_and_stem:spawns/*}), so datapacks can move everything.
 */
public final class FabricWorldgen {
    private static final String MANIFEST = "/spore_and_stem/biome_modifications.json";

    private FabricWorldgen() {
    }

    public static void init() {
        JsonObject manifest = read();
        int features = 0;
        int spawns = 0;
        for (JsonElement element : manifest.getAsJsonArray("features")) {
            JsonObject entry = element.getAsJsonObject();
            ResourceKey<PlacedFeature> feature = ResourceKey.create(Registries.PLACED_FEATURE,
                    new ResourceLocation(entry.get("feature").getAsString()));
            GenerationStep.Decoration step = GenerationStep.Decoration.valueOf(
                    entry.get("step").getAsString().toUpperCase(Locale.ROOT));
            BiomeModifications.addFeature(BiomeSelectors.tag(biomeTag(entry)), step, feature);
            features++;
        }
        for (JsonElement element : manifest.getAsJsonArray("spawns")) {
            JsonObject entry = element.getAsJsonObject();
            ResourceLocation id = new ResourceLocation(entry.get("entity").getAsString());
            EntityType<?> type = BuiltInRegistries.ENTITY_TYPE.getOptional(id)
                    .orElseThrow(() -> new IllegalStateException("Unknown entity type in worldgen manifest: " + id));
            MobCategory category = MobCategory.valueOf(entry.get("category").getAsString().toUpperCase(Locale.ROOT));
            BiomeModifications.addSpawn(BiomeSelectors.tag(biomeTag(entry)), category, type,
                    entry.get("weight").getAsInt(), entry.get("min").getAsInt(), entry.get("max").getAsInt());
            spawns++;
        }
        SporeAndStem.LOGGER.debug("Added {} placed features and {} spawns to biomes", features, spawns);
    }

    private static TagKey<Biome> biomeTag(JsonObject entry) {
        return TagKey.create(Registries.BIOME, new ResourceLocation(entry.get("biomes").getAsString()));
    }

    private static JsonObject read() {
        try (InputStream in = FabricWorldgen.class.getResourceAsStream(MANIFEST)) {
            if (in == null) {
                throw new IllegalStateException("Missing " + MANIFEST + " (run tools/assets/build.py)");
            }
            try (Reader reader = new InputStreamReader(in, StandardCharsets.UTF_8)) {
                return JsonParser.parseReader(reader).getAsJsonObject();
            }
        } catch (IOException e) {
            throw new IllegalStateException("Could not read " + MANIFEST, e);
        }
    }
}
